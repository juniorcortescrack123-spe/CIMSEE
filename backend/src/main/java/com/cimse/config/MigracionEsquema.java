package com.cimse.config;

import jakarta.annotation.PostConstruct;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * Al iniciar, agrega las tablas y columnas nuevas de la revision del 27 de octubre sin borrar datos:
 * varios roles por usuario, vigencia de la clave temporal, contactos de cliente y documentos de contrato.
 * Todas las sentencias son idempotentes. Si alguna falla (por ejemplo por permisos) solo se avisa en el log.
 */
@Component
public class MigracionEsquema {

    private static final Logger LOG = LoggerFactory.getLogger(MigracionEsquema.class);
    private final JdbcTemplate jdbc;

    public MigracionEsquema(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    @PostConstruct
    public void migrar() {
        String[] sentencias = {
            "ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS clave_expira TIMESTAMP",

            // Sprint 4: busqueda rapida de las alertas del centro de notificaciones
            "CREATE INDEX IF NOT EXISTS idx_alertas_clave ON alertas_vencimiento (tipo_entidad, id_referencia, fecha_vencimiento)",

            // empleados creados antes del arreglo quedaron con estado vacio y no aparecian para crearles usuario
            "UPDATE empleados SET activo = 'S' WHERE activo IS NULL AND fecha_retiro IS NULL",
            "UPDATE empleados SET estado_candidato = 'CONTRATADO' WHERE estado_candidato IS NULL",
            "UPDATE empleados SET fecha_ingreso = CURRENT_DATE WHERE fecha_ingreso IS NULL",

            // bloqueo de cuenta tras 3 intentos fallidos
            "ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS intentos_fallidos INTEGER DEFAULT 0",
            "ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS bloqueado CHAR(1) DEFAULT 'N'",
            "ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS fecha_bloqueo TIMESTAMP",
            "ALTER TABLE solicitudes_clave ADD COLUMN IF NOT EXISTS motivo VARCHAR(15) DEFAULT 'OLVIDO'",

            "CREATE TABLE IF NOT EXISTS usuario_roles ("
                + "id_usuario INTEGER NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE, "
                + "id_rol INTEGER NOT NULL REFERENCES roles(id_rol) ON DELETE CASCADE, "
                + "PRIMARY KEY (id_usuario, id_rol))",

            // solo la primera vez: cada usuario conserva su rol actual como rol principal
            "INSERT INTO usuario_roles (id_usuario, id_rol) "
                + "SELECT u.id_usuario, r.id_rol FROM usuarios u JOIN roles r ON r.nombre = u.rol "
                + "WHERE NOT EXISTS (SELECT 1 FROM usuario_roles)",

            "CREATE TABLE IF NOT EXISTS cliente_contactos ("
                + "id_contacto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "id_cliente INTEGER NOT NULL REFERENCES clientes(id_cliente) ON DELETE CASCADE, "
                + "nombre VARCHAR(100) NOT NULL, cargo VARCHAR(60), telefono_celular VARCHAR(20), correo VARCHAR(100))",

            "CREATE TABLE IF NOT EXISTS contrato_documentos ("
                + "id_documento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "id_contrato INTEGER NOT NULL REFERENCES contratos(id_contrato) ON DELETE CASCADE, "
                + "nombre_archivo VARCHAR(200) NOT NULL, ruta_archivo VARCHAR(400) NOT NULL, tamanio BIGINT, "
                + "fecha_subida TIMESTAMP DEFAULT CURRENT_TIMESTAMP, id_usuario_subio INTEGER)",

            // ---------- Revision del 3 de noviembre: visitas de supervision, incidencias y catalogos de inventario ----------
            "CREATE TABLE IF NOT EXISTS supervisor_clientes (id_supervisor INTEGER NOT NULL REFERENCES empleados(id_empleado), "
                + "id_cliente INTEGER NOT NULL REFERENCES clientes(id_cliente), PRIMARY KEY (id_supervisor, id_cliente))",
            "CREATE TABLE IF NOT EXISTS visitas_supervision (id_visita INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "id_supervisor INTEGER NOT NULL REFERENCES empleados(id_empleado), "
                + "id_cliente INTEGER NOT NULL REFERENCES clientes(id_cliente), "
                + "fecha_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP, observaciones VARCHAR(500))",
            "ALTER TABLE supervision_operativa ADD COLUMN IF NOT EXISTS id_visita INTEGER REFERENCES visitas_supervision(id_visita)",
            "ALTER TABLE supervision_operativa ADD COLUMN IF NOT EXISTS tipo_falta VARCHAR(20)",
            "ALTER TABLE supervision_operativa ADD COLUMN IF NOT EXISTS motivo_falta VARCHAR(50)",
            "ALTER TABLE incidencias ADD COLUMN IF NOT EXISTS nivel VARCHAR(20) DEFAULT 'GUARDIA'",
            "ALTER TABLE incidencias ADD COLUMN IF NOT EXISTS id_cliente INTEGER REFERENCES clientes(id_cliente)",
            "ALTER TABLE incidencias ADD COLUMN IF NOT EXISTS id_visita INTEGER REFERENCES visitas_supervision(id_visita)",
            "ALTER TABLE incidencias ADD COLUMN IF NOT EXISTS id_empleado_afectado INTEGER REFERENCES empleados(id_empleado)",
            "ALTER TABLE incidencias DROP CONSTRAINT IF EXISTS incidencias_tipo_check",
            "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_incidencias_tipo') THEN "
                + "ALTER TABLE incidencias ADD CONSTRAINT chk_incidencias_tipo CHECK (tipo IN ('AUSENCIA', 'LLEGADA_TARDIA', "
                + "'PROBLEMA_CLIENTE', 'INCIDENTE_SEGURIDAD', 'DANO_PROPIEDAD', 'PERDIDA_ROBO_EQUIPO', 'ASALTO', 'OTRO')); END IF; END $$",
            "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_incidencias_nivel') THEN "
                + "ALTER TABLE incidencias ADD CONSTRAINT chk_incidencias_nivel CHECK (nivel IN ('GUARDIA', 'ESTABLECIMIENTO')); END IF; END $$",
            "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_sup_tipo_falta') THEN "
                + "ALTER TABLE supervision_operativa ADD CONSTRAINT chk_sup_tipo_falta CHECK (tipo_falta IN ('CON_EXCUSA', 'SIN_EXCUSA')); END IF; END $$",

            // tipos de activo y ubicaciones: listas que administra el administrador
            "CREATE TABLE IF NOT EXISTS tipos_activo (codigo VARCHAR(30) PRIMARY KEY, nombre VARCHAR(60) NOT NULL, "
                + "activo CHAR(1) DEFAULT 'S', es_sistema CHAR(1) DEFAULT 'N')",
            "INSERT INTO tipos_activo (codigo, nombre, es_sistema) VALUES ('ARMA', 'Arma de fuego', 'S'), "
                + "('VEHICULO', 'Vehiculo / motocicleta', 'S'), ('UNIFORME', 'Uniforme', 'S'), "
                + "('EQUIPO_PROTECCION', 'Equipo de proteccion', 'S') ON CONFLICT DO NOTHING",
            "ALTER TABLE inventario_activos DROP CONSTRAINT IF EXISTS inventario_activos_tipo_activo_check",
            "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_activo_tipo') THEN "
                + "ALTER TABLE inventario_activos ADD CONSTRAINT fk_activo_tipo FOREIGN KEY (tipo_activo) REFERENCES tipos_activo(codigo); END IF; END $$",
            "CREATE TABLE IF NOT EXISTS ubicaciones_inventario (id_ubicacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "nombre VARCHAR(100) NOT NULL UNIQUE, activo CHAR(1) DEFAULT 'S')",
            "INSERT INTO ubicaciones_inventario (nombre) VALUES ('Almacen principal'), ('Armeria'), ('Almacen San Pedro Sula'), "
                + "('Parqueo y flota') ON CONFLICT DO NOTHING",
            // lo que ya estaba escrito a mano en los activos pasa a la lista, para no perder nada
            "INSERT INTO ubicaciones_inventario (nombre) SELECT DISTINCT TRIM(ubicacion_actual) FROM inventario_activos "
                + "WHERE ubicacion_actual IS NOT NULL AND TRIM(ubicacion_actual) <> '' ON CONFLICT DO NOTHING",

            // permiso VISITAS: el supervisor ve solo sus visitas e incidencias (solo la primera vez)
            "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM permisos WHERE codigo = 'VISITAS') THEN "
                + "INSERT INTO permisos (codigo, descripcion) VALUES ('VISITAS', 'Visitas de supervision e incidencias de campo'); "
                + "INSERT INTO rol_permisos (id_rol, codigo_permiso) SELECT id_rol, 'VISITAS' FROM roles "
                + "WHERE nombre IN ('ADMINISTRADOR', 'GERENTE_GENERAL', 'GERENTE_OPERACIONES', 'SUPERVISOR') ON CONFLICT DO NOTHING; "
                + "DELETE FROM rol_permisos WHERE codigo_permiso IN ('SUPERVISION', 'EQUIPOS') "
                + "AND id_rol IN (SELECT id_rol FROM roles WHERE nombre = 'SUPERVISOR'); END IF; END $$",

            // ---------- Portal del guardia ----------
            "CREATE TABLE IF NOT EXISTS solicitudes_guardia (id_solicitud INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "id_empleado INTEGER NOT NULL REFERENCES empleados(id_empleado), "
                + "id_supervisor INTEGER NOT NULL REFERENCES empleados(id_empleado), "
                + "tipo VARCHAR(25) NOT NULL CHECK (tipo IN ('CAMBIO_TURNO', 'CAMBIO_EQUIPO', 'DEVOLUCION_EQUIPO')), "
                + "id_turno_solicitado INTEGER REFERENCES turnos(id_turno), id_activo INTEGER REFERENCES inventario_activos(id_activo), "
                + "motivo VARCHAR(300) NOT NULL, fecha_solicitud TIMESTAMP DEFAULT CURRENT_TIMESTAMP, "
                + "estado VARCHAR(15) DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA')), "
                + "respuesta VARCHAR(300), fecha_respuesta TIMESTAMP, id_usuario_respondio INTEGER REFERENCES usuarios(id_usuario), "
                + "visto_guardia CHAR(1) DEFAULT 'N' CHECK (visto_guardia IN ('S', 'N')))",
            "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM permisos WHERE codigo = 'PORTAL_GUARDIA') THEN "
                + "INSERT INTO permisos (codigo, descripcion) VALUES ('PORTAL_GUARDIA', 'Portal del guardia: mi puesto, solicitudes e incidencias'); "
                + "INSERT INTO rol_permisos (id_rol, codigo_permiso) SELECT id_rol, 'PORTAL_GUARDIA' FROM roles WHERE nombre = 'GUARDIA' ON CONFLICT DO NOTHING; "
                + "END IF; END $$",

            // ---------- Vacaciones del guardia ----------
            "ALTER TABLE solicitudes_guardia ADD COLUMN IF NOT EXISTS fecha_inicio DATE",
            "ALTER TABLE solicitudes_guardia ADD COLUMN IF NOT EXISTS fecha_fin DATE",
            "ALTER TABLE solicitudes_guardia DROP CONSTRAINT IF EXISTS solicitudes_guardia_tipo_check",
            "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_solg_tipo') THEN "
                + "ALTER TABLE solicitudes_guardia ADD CONSTRAINT chk_solg_tipo CHECK (tipo IN ('CAMBIO_TURNO', 'CAMBIO_EQUIPO', "
                + "'DEVOLUCION_EQUIPO', 'VACACIONES')); END IF; END $$",

            // ---------- Permisos propios de Compras, Permisos legales y Cadena relacional + rol ADMINISTRATIVO (solo la primera vez) ----------
            "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM permisos WHERE codigo = 'COMPRAS') THEN "
                + "INSERT INTO permisos (codigo, descripcion) VALUES ('COMPRAS', 'Compras e insumos'), "
                + "('PERMISOS_LEGALES', 'Permisos legales (alcaldia, armeria, operacion)'), "
                + "('CADENA', 'Cadena relacional cliente - contrato - puesto - guardia') ON CONFLICT DO NOTHING; "
                + "INSERT INTO rol_permisos (id_rol, codigo_permiso) SELECT id_rol, 'COMPRAS' FROM rol_permisos WHERE codigo_permiso = 'PROVEEDORES' ON CONFLICT DO NOTHING; "
                + "INSERT INTO rol_permisos (id_rol, codigo_permiso) SELECT id_rol, 'PERMISOS_LEGALES' FROM rol_permisos WHERE codigo_permiso = 'PAGOS' ON CONFLICT DO NOTHING; "
                + "INSERT INTO rol_permisos (id_rol, codigo_permiso) SELECT r.id_rol, p.codigo FROM roles r CROSS JOIN permisos p "
                + "WHERE r.nombre = 'ADMINISTRADOR' AND p.codigo IN ('COMPRAS', 'PERMISOS_LEGALES', 'CADENA') ON CONFLICT DO NOTHING; "
                + "INSERT INTO roles (nombre, descripcion, activo, es_sistema) VALUES ('ADMINISTRATIVO', "
                + "'Personal administrativo: reportes, compras, pagos, activos, contratos y cadena relacional', 'S', 'S') ON CONFLICT DO NOTHING; "
                + "INSERT INTO rol_permisos (id_rol, codigo_permiso) SELECT r.id_rol, v.codigo FROM roles r CROSS JOIN "
                + "(VALUES ('REPORTES'), ('COMPRAS'), ('PAGOS'), ('INVENTARIO'), ('CONTRATOS'), ('CADENA')) AS v(codigo) "
                + "WHERE r.nombre = 'ADMINISTRATIVO' ON CONFLICT DO NOTHING; END IF; END $$"
        };
        for (String sql : sentencias) {
            try {
                jdbc.execute(sql);
            } catch (Exception e) {
                LOG.warn("Migracion omitida ({}): {}", sql.substring(0, Math.min(60, sql.length())), e.getMessage());
            }
        }
    }
}
