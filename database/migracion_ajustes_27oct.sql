
-- ---------- 10. AJUSTES DE LA REVISION (27 de octubre): varios roles por usuario, clave temporal, contactos y documentos ----------
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS clave_expira TIMESTAMP;

CREATE TABLE IF NOT EXISTS usuario_roles (
    id_usuario INTEGER NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    id_rol INTEGER NOT NULL REFERENCES roles(id_rol) ON DELETE CASCADE,
    PRIMARY KEY (id_usuario, id_rol)
);

CREATE TABLE IF NOT EXISTS cliente_contactos (
    id_contacto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL REFERENCES clientes(id_cliente) ON DELETE CASCADE,
    nombre VARCHAR(100) NOT NULL,
    cargo VARCHAR(60),
    telefono_celular VARCHAR(20),
    correo VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS contrato_documentos (
    id_documento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_contrato INTEGER NOT NULL REFERENCES contratos(id_contrato) ON DELETE CASCADE,
    nombre_archivo VARCHAR(200) NOT NULL,
    ruta_archivo VARCHAR(400) NOT NULL,
    tamanio BIGINT,
    fecha_subida TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    id_usuario_subio INTEGER
);

